panel("業務シミュレーション", "予測の先にある意思決定を扱う場所")

st.markdown(
    """
ラボ 11 までは「予測が当たっているか」で話が終わっていました。実務はそこで終わりません。

- **需要を当てること自体は目的ではない** — 目的は「何個仕入れるか」を決めること
- **評価は精度ではなく円で出る** — RMSE が下がっても利益が増えるとは限らない

**ラボ 12（在庫・発注）** では、1 個余った損と 1 個足りなかった損が違う額のとき、
**RMSE を最小にする予測が利益を最大にしない**ことを金額で確かめられます。
狙うべきは平均ではなく、臨界比 `Cu/(Cu+Co)` に対応する分位点です。

真の需要を知っている**オラクル**を並走させているので、
「予測をこれ以上頑張って、あといくら取れるのか」という上限も出ます。
オラクルとの差は *予測のせいの損* と *決め方のせいの損* に分けて表示されます。
**次にモデルを磨くべきか、ルールを直すべきか**がここで決まります。
"""
)

