panel("使い方", "3 つだけ覚えれば十分です")

st.markdown(
    """
1. **左のサイドバーを動かす** — データの形・ノイズ・ハイパーパラメータはすべてここにあります。
   1 つだけ動かして、図がどう変わるかを見るのがコツです。
2. **図の下の解説を読む** — 各ラボの下部に、いま見ているものの意味と
   「どこを見ればいいか」を書いてあります。
3. **乱数シードを変えてみる** — 同じ設定でもデータが変われば結果は揺れます。
   その揺れの大きさ自体が、モデルの安定性の情報になります。
"""
)

